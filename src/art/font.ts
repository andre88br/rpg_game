/* marcas de acento, desenhadas em coordenadas relativas ao topo do glifo */
interface Marca { above?: readonly string[]; below?: readonly string[] }

const MARCAS: Record<string, Marca> = {
  acute:  { above: ['...#.', '..#..'] },
  grave:  { above: ['.#...', '..#..'] },
  circ:   { above: ['..#..', '.#.#.'] },
  tilde:  { above: ['..##.', '.##..'] },
  ced:    { below: ['..#..', '.##..'] },
};

/* letra acentuada -> letra base + marca */
const ACENTOS: Record<string, [string, string]> = {
  'Á': ['A', 'acute'], 'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ã': ['A', 'tilde'],
  'É': ['E', 'acute'], 'Ê': ['E', 'circ'],
  'Í': ['I', 'acute'],
  'Ó': ['O', 'acute'], 'Ô': ['O', 'circ'], 'Õ': ['O', 'tilde'],
  'Ú': ['U', 'acute'], 'Ü': ['U', 'circ'],
  'Ç': ['C', 'ced'],
};

export const CHAR_W = 6;   // 5px de glifo + 1px de espaco
export const LINE_H = 11;  // 7px de glifo + 2px de acento + 2px de respiro

/* largura em pixels de um texto */
export function larguraTexto(s: string): number { return s.length * CHAR_W - 1; }

/* desenha texto em um Buf. y e o topo do glifo (acentos sobem acima disso). */
export function texto(buf: Buf, s: string, x: number, y: number, cor: string,
                      opt: { sombra?: string } = {}): number {
  const { sombra = null } = opt;
  s = String(s).toUpperCase();
  let cx = x;
  for (const rawCh of s) {
    let ch = rawCh; let marca: Marca | null = null;
    if (ACENTOS[rawCh]) { ch = ACENTOS[rawCh]![0]; marca = MARCAS[ACENTOS[rawCh]![1]]!; }
    const glifo = G[ch];
    if (glifo) {
      if (sombra) desenharGlifo(buf, glifo, cx + 1, y + 1, sombra, marca);
      desenharGlifo(buf, glifo, cx, y, cor, marca);
    }
    cx += CHAR_W;
  }
  return cx;
}

function desenharGlifo(buf: Buf, glifo: readonly string[], x: number, y: number,
                       cor: string, marca: Marca | null): void {
  for (let j = 0; j < glifo.length; j++) {
    for (let i = 0; i < glifo[j]!.length; i++) {
      if (glifo[j]![i] === '#') buf.set(x + i, y + j, cor);
    }
  }
  if (!marca) return;
  if (marca.above) {
    for (let j = 0; j < marca.above.length; j++)
      for (let i = 0; i < marca.above[j]!.length; i++)
        if (marca.above[j]![i] === '#') buf.set(x + i, y - marca.above.length + j, cor);
  }
  if (marca.below) {
    for (let j = 0; j < marca.below.length; j++)
      for (let i = 0; i < marca.below[j]!.length; i++)
        if (marca.below[j]![i] === '#') buf.set(x + i, y + 7 + j, cor);
  }
}

/* quebra de texto por largura maxima em pixels, em palavras */
export function quebrar(s: string, maxPx: number): string[] {
  const palavras = String(s).split(' ');
  const linhas: string[] = []; let atual = '';
  for (const p of palavras) {
    const teste = atual ? atual + ' ' + p : p;
    if (larguraTexto(teste) > maxPx && atual) { linhas.push(atual); atual = p; }
    else atual = teste;
  }
  if (atual) linhas.push(atual);
  return linhas;
}
