/* marcas de acento, desenhadas em coordenadas relativas ao topo do glifo */
const MARKS = {
  acute:  { above: ['...#.', '..#..'] },
  grave:  { above: ['.#...', '..#..'] },
  circ:   { above: ['..#..', '.#.#.'] },
  tilde:  { above: ['..##.', '.##..'] },
  ced:    { below: ['..#..', '.##..'] },
};

/* letra acentuada -> letra base + marca */
const ACC = {
  'Á': ['A', 'acute'], 'À': ['A', 'grave'], 'Â': ['A', 'circ'], 'Ã': ['A', 'tilde'],
  'É': ['E', 'acute'], 'Ê': ['E', 'circ'],
  'Í': ['I', 'acute'],
  'Ó': ['O', 'acute'], 'Ô': ['O', 'circ'], 'Õ': ['O', 'tilde'],
  'Ú': ['U', 'acute'], 'Ü': ['U', 'circ'],
  'Ç': ['C', 'ced'],
};

export const CHAR_W = 6;   // 5px de glifo + 1px de espaco
export const LINE_H = 11;  // 7px de glifo + 2px de acento + 2px de respiro

/* largura em pixels de um texto */
export function textWidth(s) { return s.length * CHAR_W - 1; }

/* desenha texto em um Buf. y e o topo do glifo (acentos sobem acima disso). */
export function text(buf, s, x, y, color, opt = {}) {
  const { shadow = null } = opt;
  s = String(s).toUpperCase();
  let cx = x;
  for (const rawCh of s) {
    let ch = rawCh, mark = null;
    if (ACC[rawCh]) { ch = ACC[rawCh][0]; mark = MARKS[ACC[rawCh][1]]; }
    const glyph = G[ch];
    if (glyph) {
      if (shadow) drawGlyph(buf, glyph, cx + 1, y + 1, shadow, mark);
      drawGlyph(buf, glyph, cx, y, color, mark);
    }
    cx += CHAR_W;
  }
  return cx;
}

function drawGlyph(buf, glyph, x, y, color, mark) {
  for (let j = 0; j < glyph.length; j++) {
    for (let i = 0; i < glyph[j].length; i++) {
      if (glyph[j][i] === '#') buf.set(x + i, y + j, color);
    }
  }
  if (!mark) return;
  if (mark.above) {
    for (let j = 0; j < mark.above.length; j++)
      for (let i = 0; i < mark.above[j].length; i++)
        if (mark.above[j][i] === '#') buf.set(x + i, y - mark.above.length + j, color);
  }
  if (mark.below) {
    for (let j = 0; j < mark.below.length; j++)
      for (let i = 0; i < mark.below[j].length; i++)
        if (mark.below[j][i] === '#') buf.set(x + i, y + 7 + j, color);
  }
}

/* quebra de texto por largura maxima em pixels, em palavras */
export function wrap(s, maxPx) {
  const words = String(s).split(' ');
  const lines = []; let cur = '';
  for (const w of words) {
    const test = cur ? cur + ' ' + w : w;
    if (textWidth(test) > maxPx && cur) { lines.push(cur); cur = w; }
    else cur = test;
  }
  if (cur) lines.push(cur);
  return lines;
}
